import { describe, expect, it } from 'vitest';
import { articulatedChestPress, createInitialState } from './data';
import { createBackup, createSession, parseBackup, validateState } from './domain';
import { migrateState } from './migrations';

function legacyState() {
  const state = createInitialState();
  delete state.routineRevision;
  delete state.exerciseNotes;
  state.workouts[0].exercises = state.workouts[0].exercises.filter(e => e.id !== 'articulated-chest-press');
  state.workouts[0].exercises[1] = { ...state.workouts[0].exercises[1], name: 'Supino inclinado na máquina', image: 1 };
  state.workouts[1].image = 6;
  state.workouts[1].exercises[0] = { ...state.workouts[1].exercises[0], id: 'pullup', name: 'Barra fixa pronada', image: 6, target: '6–10' };
  state.workouts[1].exercises[2] = { ...state.workouts[1].exercises[2], name: 'Remada articulada com apoio para peito', image: 8 };
  state.workouts[1].exercises[5] = { ...state.workouts[1].exercises[5], id: 'hammer-curl', name: 'Rosca martelo com halteres', image: 11 };
  state.weights = { 'bench-press': 42.5, 'incline-machine': 35, 'pullup': 5, 'hammer-curl': 12 };
  return state;
}

describe('existing installation upgrades', () => {
  it('updates known routine entries without resetting loads or inheriting a different exercise load', () => {
    const old = legacyState();
    const state = migrateState(old);
    expect(state.weights).toEqual(old.weights);
    expect(state.workouts[0].exercises[1].name).toBe('Supino inclinado com barra');
    expect(state.workouts[0].exercises[1].image).toBe(30);
    expect(state.workouts[1].exercises[0].id).toBe('lat-pulldown');
    expect(state.workouts[1].exercises[2].name).toContain('Hammer');
    expect(state.workouts[1].exercises[5].id).toBe('rope-curl');
    expect(createSession(state.workouts[1], state.weights).exercises[0].weight).toBe(0);
    expect(createSession(state.workouts[1], state.weights).exercises[5].weight).toBe(0);
    expect(validateState(state)).toBe(true);
    expect(migrateState(state)).toEqual(state);
    expect(old.workouts[0].exercises[1].name).toBe('Supino inclinado na máquina');
  });
  it('preserves customized names and historical snapshots', () => {
    const old = legacyState();
    old.workouts[0].exercises[1].name = 'Meu supino personalizado';
    const past = createSession(old.workouts[1], old.weights, 1000);
    past.exercises[0].done[0] = true;
    past.finishedAt = 2000;
    old.history = [past];
    const state = migrateState(old);
    expect(state.workouts[0].exercises[1].name).toBe('Meu supino personalizado');
    expect(state.history).toEqual(old.history);
    expect(state.history[0].exercises[0].name).toBe('Barra fixa pronada');
  });
  it('preserves already performed exercises in an active session while replacing unstarted ones', () => {
    const old = legacyState();
    old.active = createSession(old.workouts[1], old.weights);
    old.active.exercises[0].done[0] = true;
    const state = migrateState(old);
    expect(state.active?.exercises[0].exerciseId).toBe('pullup');
    expect(state.active?.exercises[0].done[0]).toBe(true);
    expect(state.active?.exercises[5].exerciseId).toBe('rope-curl');
    expect(state.active?.exercises[5].weight).toBe(0);
    expect(validateState(state)).toBe(true);
  });
  it('upgrades previous-version backups and includes personal notes and muscle metadata in new backups', () => {
    const state = parseBackup(createBackup(legacyState()));
    expect(state.routineRevision).toBe(12);
    expect(state.workouts[1].exercises[0].muscle).toBe('back');
    state.exerciseNotes = { 'bench-press': 'Banco na posição 3' };
    expect(parseBackup(createBackup(state))).toEqual(state);
    state.exerciseNotes['bench-press'] = 'x'.repeat(1001);
    expect(() => parseBackup(createBackup(state))).toThrow();
  });
  it('recovers a missing load from the latest relevant saved session without overriding an explicit zero', () => {
    const old = legacyState();
    const a = createSession(old.workouts[0], { 'bench-press': 40 }, 1000);
    const b = createSession(old.workouts[0], { 'bench-press': 45 }, 3000);
    a.exercises[0].done[0] = b.exercises[0].done[0] = true;
    a.finishedAt = 2000; b.finishedAt = 4000;
    old.history = [a, b];
    delete old.weights['bench-press'];
    expect(migrateState(old).weights['bench-press']).toBe(45);
    old.weights['bench-press'] = 0;
    expect(migrateState(old).weights['bench-press']).toBe(0);
  });
  it('sets three series everywhere and applies the current chest routine without changing past sessions', () => {
    const old = legacyState();
    old.workouts[0].exercises.find(e => e.id === 'pec-deck')!.sets = 2;
    const completed = createSession(old.workouts[0], old.weights, 1000);
    completed.finishedAt = 2000;
    completed.exercises.find(e => e.exerciseId === 'pec-deck')!.done = [true, true];
    old.history = [completed];
    old.active = createSession(old.workouts[0], old.weights);
    old.active.exercises.find(e => e.exerciseId === 'pec-deck')!.done = [true, false];
    const next = migrateState(old);
    expect(next.workouts.every(w => w.exercises.every(e => e.sets === 3))).toBe(true);
    expect(next.workouts[0].exercises.some(e => e.id === 'articulated-chest-press')).toBe(false);
    expect(next.workouts[0].exercises.filter(e => e.id === 'parallel-bar-dips')).toHaveLength(1);
    expect(next.active?.exercises.find(e => e.exerciseId === 'parallel-bar-dips')?.done).toEqual([false, false, false]);
    expect(next.active?.exercises.find(e => e.exerciseId === 'pec-deck')?.done).toEqual([true, false, false]);
    expect(next.history[0].exercises.find(e => e.exerciseId === 'pec-deck')?.done).toEqual([true, true]);
    expect(migrateState(next)).toEqual(next);
    expect(validateState(next)).toBe(true);
  });
  it.each([false, true])('replaces the chest machine with shared dips while preserving performed machine sets (%s)', performed => {
    const old = createInitialState();
    old.routineRevision = 9;
    const workout = old.workouts[0];
    workout.exercises = workout.exercises.filter(e => e.id !== 'parallel-bar-dips');
    workout.exercises.splice(2, 0, { ...articulatedChestPress });
    workout.exercises.find(e => e.id === 'overhead-extension')!.name = 'Tríceps acima da cabeça na polia';
    old.weights = { 'articulated-chest-press': 55, 'parallel-bar-dips': 10, 'overhead-extension': 15 };
    old.active = createSession(workout, old.weights);
    old.active.exercises.find(e => e.exerciseId === articulatedChestPress.id)!.done[0] = performed;
    const past = { ...structuredClone(old.active), finishedAt: old.active.startedAt + 60000 };
    old.history = [past];
    const next = migrateState(old);
    expect(next.workouts[0].exercises.map(e => e.id)).toEqual(['bench-press', 'incline-machine', 'pec-deck', 'parallel-bar-dips', 'rope-pushdown', 'overhead-extension']);
    expect(next.active?.exercises.some(e => e.exerciseId === articulatedChestPress.id)).toBe(performed);
    expect(next.active?.exercises.filter(e => e.exerciseId === 'parallel-bar-dips')).toHaveLength(1);
    expect(next.active?.exercises.find(e => e.exerciseId === 'parallel-bar-dips')?.weight).toBe(10);
    expect(next.active?.exercises.find(e => e.exerciseId === 'overhead-extension')).toMatchObject({ name: 'Tríceps francês na polia', weight: 15 });
    expect(next.weights).toEqual(old.weights);
    expect(next.history).toEqual([past]);
    expect(validateState(next)).toBe(true);
    expect(migrateState(next)).toEqual(next);
  });
  it('preserves a custom overhead-extension name', () => {
    const old = createInitialState();
    old.routineRevision = 9;
    old.workouts[0].exercises.find(e => e.id === 'overhead-extension')!.name = 'Meu francês personalizado';
    expect(migrateState(old).workouts[0].exercises.find(e => e.id === 'overhead-extension')?.name).toBe('Meu francês personalizado');
  });
  it('replaces stiff and knee raises with two abdominal exercises while preserving old history and loads', () => {
    const old = legacyState();
    old.workouts[2].exercises = old.workouts[2].exercises.filter(e => !['decline-situp', 'military-situp'].includes(e.id));
    old.workouts[2].exercises.push({ id: 'romanian-deadlift', name: 'Stiff / levantamento terra romeno', sets: 3, target: '8–12', image: 15, kind: 'reps', rest: 90 });
    old.workouts[2].exercises.push({ id: 'hanging-knee-raise', name: 'Elevação de joelhos ou pernas', sets: 3, target: '10–15', image: 17, kind: 'reps', rest: 90 });
    old.weights['romanian-deadlift'] = 50;
    old.active = createSession(old.workouts[2], old.weights);
    old.active.exercises.find(e => e.exerciseId === 'romanian-deadlift')!.done[0] = true;
    const next = migrateState(old);
    expect(next.workouts[2].exercises.map(e => e.id)).toEqual(['leg-press', 'leg-extension', 'leg-curl', 'calf-raise', 'decline-situp', 'military-situp']);
    expect(next.weights['romanian-deadlift']).toBe(50);
    expect(next.active?.exercises.find(e => e.exerciseId === 'romanian-deadlift')?.done[0]).toBe(true);
    expect(next.active?.exercises.some(e => e.exerciseId === 'hanging-knee-raise')).toBe(false);
    expect(next.active?.exercises.find(e => e.exerciseId === 'decline-situp')?.weight).toBe(0);
    expect(next.workouts[2].exercises.filter(e => e.muscle === 'abs')).toHaveLength(2);
    expect(migrateState(next)).toEqual(next);
    expect(validateState(next)).toBe(true);
  });
  it('replaces the machine shoulder press with triceps dips without reusing the machine load', () => {
    const old = createInitialState();
    old.routineRevision = 6;
    old.workouts[3].image = 18;
    old.workouts[3].exercises = [{ id: 'shoulder-press', name: 'Desenvolvimento de ombros na máquina', image: 18, sets: 3, target: '6–10', kind: 'reps', rest: 90, muscle: 'shoulders' }, ...old.workouts[3].exercises.filter(e => e.id !== 'parallel-bar-dips')];
    old.weights['shoulder-press'] = 30;
    old.active = createSession(old.workouts[3], old.weights);
    const next = migrateState(old);
    expect(next.workouts[3].exercises.find(e => e.id === 'parallel-bar-dips')?.muscle).toBe('triceps');
    expect(next.workouts[3].image).toBe(36);
    expect(next.active?.exercises.find(e => e.exerciseId === 'parallel-bar-dips')?.weight).toBe(0);
    expect(next.weights['shoulder-press']).toBe(30);
    expect(validateState(next)).toBe(true);
  });
  it('uses the requested Friday cover and groups the two triceps exercises while retaining active completion and loads', () => {
    const old = createInitialState();
    old.routineRevision = 8;
    old.workouts[4].image = 31;
    const workout = old.workouts[3];
    const dips = workout.exercises.find(e => e.id === 'parallel-bar-dips')!;
    workout.exercises = [dips, ...workout.exercises.filter(e => e.id !== dips.id)];
    old.weights[dips.id] = 10;
    old.active = createSession(workout, old.weights);
    old.active.exercises[0].done[0] = true;
    const savedSnapshot = { ...structuredClone(old.active), finishedAt: old.active.startedAt + 60000 };
    old.history = [savedSnapshot];
    const next = migrateState(old);
    expect(next.workouts[4].image).toBe(36);
    expect(next.workouts[4].exercises.some(e => e.id === dips.id)).toBe(false);
    expect(next.workouts[3].exercises.slice(-2).map(e => e.id)).toEqual(['parallel-bar-dips', 'bar-pushdown']);
    expect(next.active?.exercises.slice(-2).map(e => e.exerciseId)).toEqual(['parallel-bar-dips', 'bar-pushdown']);
    expect(next.active?.exercises.find(e => e.exerciseId === dips.id)?.done).toEqual([true, false, false]);
    expect(next.active?.exercises.find(e => e.exerciseId === dips.id)?.weight).toBe(10);
    expect(next.history[0]).toEqual(savedSnapshot);
    expect(validateState(next)).toBe(true);
    expect(migrateState(next)).toEqual(next);
  });
  it('moves Friday to gym back exercises and shares current loads without deleting past calisthenics records', () => {
    const old = createInitialState();
    old.routineRevision = 7;
    const friday = old.workouts[4];
    friday.name = 'Costas, bíceps + calistenia';
    friday.image = 24;
    friday.exercises = friday.exercises.filter(e => !['cable-row', 'straight-arm-pulldown'].includes(e.id));
    friday.exercises.unshift({ id: 'front-lever', name: 'Advanced tuck front lever', sets: 3, target: '5–10', image: 24, kind: 'seconds', rest: 90, muscle: 'back' }, { id: 'l-sit', name: 'L-sit nas paralelas', sets: 3, target: '5–15', image: 25, kind: 'seconds', rest: 90, muscle: 'abs' });
    old.weights['cable-row'] = 40;
    old.active = createSession(friday, old.weights);
    const next = migrateState(old);
    expect(next.workouts[4].name).toBe('Costas + bíceps');
    expect(next.workouts[4].exercises.map(e => e.id)).toEqual(['lat-pulldown', 'chest-supported-row', 'cable-row', 'straight-arm-pulldown', 'incline-curl', 'cable-curl']);
    expect(next.active?.exercises.some(e => ['front-lever', 'l-sit'].includes(e.exerciseId))).toBe(false);
    expect(next.active?.exercises.find(e => e.exerciseId === 'cable-row')?.weight).toBe(40);
    expect(validateState(next)).toBe(true);
  });
});
