const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
  const options = { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true };
  const first = await browser.newContext(options), second = await browser.newContext(options);
  const page = await first.newPage(), brother = await second.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  brother.on('pageerror', e => errors.push(e.message));
  const base = process.env.APP_URL || 'http://127.0.0.1:4174/gym-tracker/';
  const output = path.resolve('artifacts/plans-smoke');
  fs.mkdirSync(output, { recursive: true });
  const settings = p => p.getByRole('button', { name: 'Abrir ajustes', exact: true }).click();
  const backup = async (p, name) => {
    const wait = p.waitForEvent('download');
    await p.getByRole('button', { name: 'Exportar backup', exact: true }).click();
    const file = path.join(output, name + '.json');
    await (await wait).saveAs(file);
    return JSON.parse(fs.readFileSync(file, 'utf8')).data;
  };
  const choose = async (p, name) => {
    await settings(p);
    await p.getByRole('button', { name: new RegExp('^' + name) }).click();
    await p.getByRole('button', { name: 'Usar esta ficha', exact: true }).click();
    await p.getByRole('heading', { name: 'Seus treinos', exact: true }).waitFor();
  };
  try {
    await page.goto(base);
    await page.getByRole('button', { name: 'Abrir treino Peito + tríceps', exact: true }).click();
    await page.getByRole('textbox', { name: 'Carga de Supino reto com barra', exact: true }).fill('42');
    await settings(page);
    await page.getByRole('button', { name: 'Editar Peito + tríceps', exact: true }).click();
    await page.getByLabel('Nome do treino', { exact: true }).fill('Meu peito original');
    await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    const original = await backup(page, 'original');
    await brother.goto(base);
    await settings(brother);
    await brother.getByRole('button', { name: /^Nick/ }).click();
    await brother.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.deepEqual((await backup(brother, 'cancelled')).workouts.map(w => w.exercises.length), [6, 6, 6, 6, 6]);
    await choose(brother, 'Nick');
    await settings(brother);
    const sheet = await backup(brother, 'sheet');
    assert.equal(sheet.selectedPlan, 'sheet');
    assert.deepEqual(sheet.workouts.map(w => w.exercises.length), [8, 9, 8, 7, 8]);
    assert.deepEqual(sheet.weights, {});
    assert.deepEqual((await backup(page, 'still-original')).workouts, original.workouts);
    await brother.getByRole('button', { name: 'Editar Peito + tríceps', exact: true }).click();
    assert.equal(await brother.getByLabel('Séries', { exact: true }).first().inputValue(), '4');
    await brother.getByLabel('Nome do treino', { exact: true }).fill('Peito da folha editado');
    await brother.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    await brother.getByRole('button', { name: 'Treinos', exact: true }).click();
    await brother.getByRole('button', { name: 'Abrir treino Peito da folha editado', exact: true }).click();
    assert.equal(await brother.locator('.exercise-row').count(), 8);
    assert.equal(await brother.locator('.exercise-row').first().locator('.set-button').count(), 4);
    assert.match(await brother.locator('.exercise-instructions').first().textContent(), /MAX/);
    assert.equal(await brother.locator('.exercise-row').nth(5).locator('.set-button').count(), 3);
    await brother.locator('.exercise-image').evaluateAll(images => Promise.all(images.map(img => img.decode())));
    for (const width of [320, 390, 1280]) {
      await brother.setViewportSize({ width, height: 844 });
      assert.equal(await brother.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    }
    await brother.setViewportSize({ width: 390, height: 844 });
    await brother.getByRole('button', { name: 'Concluir série 4 de Supino inclinado com halteres', exact: true }).click();
    await settings(brother);
    assert.equal(await brother.getByRole('button', { name: /^Bruno/ }).isDisabled(), true);
    await brother.getByText('Salvo no aparelho', { exact: true }).waitFor();
    await brother.reload();
    await brother.locator('.resume-banner').click();
    assert.equal(await brother.locator('.exercise-row').first().locator('.set-button[aria-pressed=true]').count(), 4);
    await brother.getByRole('button', { name: 'Finalizar treino', exact: true }).click();
    await brother.getByRole('button', { name: 'Salvar e finalizar', exact: true }).click();
    await choose(brother, 'Bruno');
    await choose(brother, 'Nick');
    await settings(brother);
    const returned = await backup(brother, 'returned');
    assert.equal(returned.workouts[0].name, 'Peito da folha editado');
    assert.equal(returned.history.length, 1);
    assert.equal(returned.history[0].exercises[0].done.length, 4);
    await brother.screenshot({ path: path.join(output, 'routine-choice-mobile.png'), fullPage: true });
    await brother.evaluate(() => navigator.serviceWorker.ready);
    await brother.reload();
    await brother.waitForFunction(() => !!navigator.serviceWorker.controller);
    await second.setOffline(true);
    await brother.reload();
    await brother.getByRole('button', { name: 'Abrir treino Abdômen', exact: true }).click();
    assert.equal(await brother.locator('.exercise-row').count(), 8);
    assert.match(await brother.locator('.exercise-instructions').last().textContent(), /Tri-set/);
    await brother.locator('.exercise-image').evaluateAll(images => Promise.all(images.map(img => img.decode())));
    await page.reload();
    await settings(page);
    const final = await backup(page, 'unchanged-original');
    assert.deepEqual(final, original);
    assert.deepEqual(errors, []);
    console.log('PASS: separate-device choices, exact sheet series, editable metadata, confirmation/cancellation, active-session guard, preserved original routine and loads, per-plan edits, history, reload and offline access.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
