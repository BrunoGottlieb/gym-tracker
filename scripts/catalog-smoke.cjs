const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true });
  await context.route('**/api/streaks', route => route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const output = path.resolve('artifacts/catalog-smoke');
  fs.mkdirSync(output, { recursive: true });
  const base = process.env.APP_URL || 'http://127.0.0.1:4174/gym-tracker/';
  const edit = async () => {
    await page.getByRole('button', { name: 'Abrir ajustes', exact: true }).click();
    await page.getByRole('button', { name: 'Editar Peito + tríceps', exact: true }).click();
  };
  const backup = async name => {
    const waiting = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar backup', exact: true }).click();
    const file = path.join(output, name + '.json');
    await (await waiting).saveAs(file);
    return JSON.parse(fs.readFileSync(file, 'utf8')).data;
  };
  try {
    await page.goto(base);
    await page.getByRole('heading', { name: 'Seus treinos', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Abrir ajustes', exact: true }).click();
    const original = await backup('before');
    assert.deepEqual(original.workouts.map(w => w.exercises.length), [6, 6, 6, 6, 6]);
    await edit();
    await page.getByRole('button', { name: 'Adicionar exercício', exact: true }).click();
    const names = await page.locator('.picker-option strong').allTextContents();
    assert.deepEqual(names, [...names].sort((a, b) => a.localeCompare(b, 'pt-BR', { sensitivity: 'base' })));
    assert.equal(await page.getByRole('button', { name: 'Já no treino: Supino reto com barra', exact: true }).isDisabled(), true);
    for (const width of [320, 390, 1280]) {
      await page.setViewportSize({ width, height: 844 });
      assert.equal(await page.getByRole('dialog').evaluate(el => el.scrollWidth > el.clientWidth), false, 'Editor overflows at ' + width);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('searchbox', { name: 'Buscar exercício', exact: true }).fill('zzzzzz');
    await page.getByText(/Nenhum exercício encontrado/).waitFor();
    await page.getByRole('searchbox', { name: 'Buscar exercício', exact: true }).fill('bulgaro');
    await page.locator('.picker-option img').evaluate(el => el.decode());
    await page.screenshot({ path: path.join(output, 'catalog-search-mobile.png') });
    await page.getByRole('button', { name: 'Selecionar: Agachamento búlgaro', exact: true }).click();
    const added = page.locator('.editor-exercise').last();
    assert.equal(await added.getByLabel('Nome', { exact: true }).inputValue(), 'Agachamento búlgaro');
    assert.equal(await added.getByLabel('Grupo muscular principal').inputValue(), 'legs');
    assert.equal(await added.getByLabel('Ilustração').inputValue(), '44');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.deepEqual((await backup('cancelled')).workouts, original.workouts);
    await edit();
    await page.locator('.editor-exercise').first().getByRole('button', { name: 'Escolher exercício do catálogo', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Buscar exercício', exact: true }).fill('isometrico');
    await page.getByRole('button', { name: 'Selecionar: Agachamento isométrico', exact: true }).click();
    const first = page.locator('.editor-exercise').first();
    assert.equal(await first.getByLabel('Tipo').inputValue(), 'seconds');
    assert.equal(await first.getByLabel('Meta', { exact: true }).inputValue(), '30–45');
    assert.equal(await first.getByLabel('Grupo muscular principal').inputValue(), 'legs');
    await page.getByRole('button', { name: 'Adicionar exercício', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Buscar exercício', exact: true }).fill('reta polia');
    await page.getByRole('button', { name: 'Selecionar: Rosca direta com barra reta na polia', exact: true }).click();
    await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    const saved = await backup('saved');
    assert.equal(saved.workouts[0].exercises[0].id, 'wall-sit');
    assert.equal(saved.workouts[0].exercises[6].image, 57);
    assert.deepEqual(saved.workouts.slice(1), original.workouts.slice(1));
    assert.deepEqual(saved.weights, original.weights);
    assert.deepEqual(saved.history, original.history);
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload();
    await page.waitForFunction(() => !!navigator.serviceWorker.controller);
    await context.setOffline(true);
    await page.reload();
    await edit();
    await page.getByRole('button', { name: 'Adicionar exercício', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Buscar exercício', exact: true }).fill('scott maquina');
    await page.locator('.picker-option img').evaluate(el => el.decode());
    await page.getByRole('button', { name: 'Selecionar: Rosca Scott na máquina', exact: true }).click();
    await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    await page.getByRole('button', { name: 'Treinos', exact: true }).click();
    await page.getByRole('button', { name: 'Abrir treino Peito + tríceps', exact: true }).click();
    assert.equal(await page.locator('.exercise-row').count(), 8);
    await page.locator('.exercise-image').evaluateAll(images => Promise.all(images.map(el => el.decode())));
    await page.screenshot({ path: path.join(output, 'selected-exercises-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: alphabetical searchable presets, metadata, duplicate guard, cancellation, replacement, saving, unchanged routines/loads/history, mobile layout and offline catalog images.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
